import os
import re
import json
import subprocess
from pathlib import Path

WORKSPACE = Path(r"c:\Users\pavlo\scrapler")
OUTPUT_DIR = WORKSPACE / "youta_25_truths"
RAW_DIR = OUTPUT_DIR / "raw_vtt"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
RAW_DIR.mkdir(parents=True, exist_ok=True)

PLAYLIST_URL = "https://www.youtube.com/playlist?list=PLbthMJn6gI6kuw4taAaZUP-lJ_1I45A45"

def clean_vtt_to_text(vtt_path: Path) -> str:
    with open(vtt_path, "r", encoding="utf-8") as f:
        content = f.read()

    lines = content.splitlines()
    text_lines = []
    
    for line in lines:
        line = line.strip()
        if not line:
            continue
        if line.startswith("WEBVTT") or line.startswith("Kind:") or line.startswith("Language:"):
            continue
        if "-->" in line:
            continue
        # Remove timestamps and span tags like <00:00:00.520><c> or </c>
        cleaned = re.sub(r"<[^>]+>", "", line).strip()
        if cleaned:
            # Avoid consecutive duplicate lines commonly generated by YouTube rolling captions
            if not text_lines or cleaned != text_lines[-1]:
                text_lines.append(cleaned)

    # Join into coherent paragraphs
    # Sentences typically end with '.', '!', '?'
    text = " ".join(text_lines)
    # Basic cleanup of multiple spaces
    text = re.sub(r"\s+", " ", text).strip()
    return text

def main():
    print("Fetching playlist items...")
    cmd = ["yt-dlp", "--flat-playlist", "-J", PLAYLIST_URL]
    res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", check=True)
    playlist_data = json.loads(res.stdout)
    entries = playlist_data.get("entries", [])
    print(f"Found {len(entries)} videos in playlist.")

    all_lectures = []
    total_words = 0

    for idx, entry in enumerate(entries, 1):
        vid_id = entry.get("id")
        title = entry.get("title", f"Video {idx}")
        url = f"https://www.youtube.com/watch?v={vid_id}"
        print(f"\n[{idx:02d}/{len(entries)}] Processing: {title} ({vid_id})")

        vtt_template = RAW_DIR / f"{idx:02d}_{vid_id}.%(ext)s"
        target_vtt = RAW_DIR / f"{idx:02d}_{vid_id}.uk.vtt"

        if not target_vtt.exists():
            dl_cmd = [
                "yt-dlp",
                "--write-auto-sub",
                "--sub-lang", "uk,uk-orig",
                "--skip-download",
                "--sub-format", "vtt",
                "-o", str(vtt_template),
                url
            ]
            dl_res = subprocess.run(dl_cmd, capture_output=True, text=True, encoding="utf-8")
            if dl_res.returncode != 0:
                print(f"  Warning: yt-dlp error for {vid_id}: {dl_res.stderr[:200]}")

        # Check if vtt downloaded (could be .uk.vtt or .uk-orig.vtt)
        vtt_candidates = list(RAW_DIR.glob(f"{idx:02d}_{vid_id}*.vtt"))
        if not vtt_candidates:
            print(f"  ERROR: No VTT file found for {vid_id}")
            lecture_text = "[Транскрипт недоступний]"
        else:
            chosen_vtt = vtt_candidates[0]
            lecture_text = clean_vtt_to_text(chosen_vtt)

        words = len(lecture_text.split())
        total_words += words
        print(f"  Extracted {words} words.")

        # Save individual markdown file
        safe_title = re.sub(r'[\\/*?:"<>|]', "", title).replace(" ", "_")
        single_md_path = OUTPUT_DIR / f"{idx:02d}_{safe_title}.md"
        with open(single_md_path, "w", encoding="utf-8") as f:
            f.write(f"# {title}\n\n")
            f.write(f"- **URL**: {url}\n")
            f.write(f"- **Номер у курсі**: {idx}/25\n")
            f.write(f"- **Кількість слів**: {words}\n\n")
            f.write("## Повний текст (дослівно):\n\n")
            f.write(lecture_text + "\n")

        all_lectures.append({
            "index": idx,
            "id": vid_id,
            "title": title,
            "url": url,
            "words": words,
            "text": lecture_text
        })

    # Save compiled single document
    compiled_path = OUTPUT_DIR / "ALL_25_LESSONS_FULL_TRANSCRIPT.md"
    with open(compiled_path, "w", encoding="utf-8") as f:
        f.write("# 25 Істин YouTube-креатора (YOUTA) — Повний транскрипт курсу\n\n")
        f.write(f"- **Загальна кількість лекцій**: {len(all_lectures)}\n")
        f.write(f"- **Загальна кількість слів**: {total_words}\n")
        f.write(f"- **Джерело**: [{PLAYLIST_URL}]({PLAYLIST_URL})\n\n")
        f.write("## Зміст курсу\n\n")
        for lec in all_lectures:
            f.write(f"{lec['index']}. [{lec['title']}](#лекція-{lec['index']}-{lec['id']}) ({lec['words']} слів)\n")
        f.write("\n---\n\n")

        for lec in all_lectures:
            f.write(f"## Лекція {lec['index']}: {lec['title']} <a id='лекція-{lec['index']}-{lec['id']}'></a>\n\n")
            f.write(f"- **Відео**: [{lec['url']}]({lec['url']})\n")
            f.write(f"- **Обсяг**: {lec['words']} слів\n\n")
            f.write("### Текст лекції:\n\n")
            f.write(lec["text"] + "\n\n")
            f.write("---\n\n")

    print(f"\nFinished! Total words across 25 lectures: {total_words}")
    print(f"Saved individual files in: {OUTPUT_DIR}")
    print(f"Saved compiled master file: {compiled_path}")

if __name__ == "__main__":
    main()
